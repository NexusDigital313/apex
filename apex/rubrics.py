"""Rubric model + loader.

A rubric encodes "the highest standard" for one domain: the controls that define
it, the deterministic shell blocks APEX can mechanically inject, and the guidance
the LLM uses to do the intelligent rewrite. Rubrics live as JSON under rubrics/
so they can be edited (or regenerated by the design workflow) without touching code.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from typing import Dict, List, Optional

RUBRIC_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "rubrics")


@dataclass
class Control:
    id: str
    title: str
    severity: str
    rationale: str
    check: str
    fix: str
    applies_to: str
    automatable: bool

    @classmethod
    def from_dict(cls, d: Dict) -> "Control":
        return cls(
            id=d.get("id", ""),
            title=d.get("title", ""),
            severity=d.get("severity", ""),
            rationale=d.get("rationale", ""),
            check=d.get("check", ""),
            fix=d.get("fix", ""),
            applies_to=d.get("applies_to", ""),
            automatable=bool(d.get("automatable", False)),
        )


@dataclass
class Transform:
    id: str
    description: str
    trigger: str
    implementation: str
    placement: str  # normalized to "preamble" or "append"

    @classmethod
    def from_dict(cls, d: Dict) -> "Transform":
        raw = str(d.get("placement", "preamble")).lower()
        append_words = ("append", "end of", "bottom", "final", "last", "seal")
        placement = "append" if any(w in raw for w in append_words) else "preamble"
        return cls(
            id=d.get("id", ""),
            description=d.get("description", ""),
            trigger=d.get("trigger", ""),
            implementation=d.get("implementation", "").rstrip("\n"),
            placement=placement,
        )


@dataclass
class Rubric:
    domain: str
    target_standard: str
    summary: str
    controls: List[Control] = field(default_factory=list)
    transforms: List[Transform] = field(default_factory=list)
    llm_guidance: str = ""
    references: List[str] = field(default_factory=list)

    @classmethod
    def from_dict(cls, d: Dict) -> "Rubric":
        return cls(
            domain=d.get("domain", ""),
            target_standard=d.get("target_standard", ""),
            summary=d.get("summary", ""),
            controls=[Control.from_dict(c) for c in d.get("controls", [])],
            transforms=[Transform.from_dict(t) for t in d.get("deterministic_transforms", [])],
            llm_guidance=d.get("llm_guidance", ""),
            references=list(d.get("references", [])),
        )

    @property
    def automatable_controls(self) -> List[Control]:
        return [c for c in self.controls if c.automatable]


def load_rubrics(rubric_dir: Optional[str] = None) -> Dict[str, Rubric]:
    """Load every rubrics/*.json into {domain_key: Rubric}."""
    directory = rubric_dir or RUBRIC_DIR
    rubrics: Dict[str, Rubric] = {}
    if not os.path.isdir(directory):
        return rubrics
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".json") or name == "classifier.json":
            continue
        path = os.path.join(directory, name)
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        key = os.path.splitext(name)[0]
        rubrics[key] = Rubric.from_dict(data)
    return rubrics
