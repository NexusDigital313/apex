"""Rubric model + loader.

A rubric encodes "the highest standard" for one domain: the controls that define
it, the deterministic shell blocks APEX can mechanically inject, and the rewrite
rules APEX can mechanically apply to the script's own lines. Rubrics live as JSON
under rubrics/ so they can be edited (or regenerated by the design workflow)
without touching code.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

RUBRIC_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "rubrics")


@dataclass
class Control:
    id: str
    title: str
    severity: str
    rationale: str
    check: str
    fix: str
    applies_to: str
    automatable: bool

    @classmethod
    def from_dict(cls, d: Dict) -> "Control":
        return cls(
            id=d.get("id", ""),
            title=d.get("title", ""),
            severity=d.get("severity", ""),
            rationale=d.get("rationale", ""),
            check=d.get("check", ""),
            fix=d.get("fix", ""),
            applies_to=d.get("applies_to", ""),
            automatable=bool(d.get("automatable", False)),
        )


@dataclass
class Transform:
    id: str
    description: str
    trigger: str
    implementation: str
    placement: str  # normalized to "preamble" or "append"
    # Machine-evaluable, content-aware gate. This is what makes the engine
    # "self-driving": instead of pasting every block, APEX reads the target
    # script and applies a transform only when the script actually needs it.
    # Recognised keys (all optional, all combined with AND):
    #   "language":     restrict to this language ("shell" | "python")
    #   "absent":       list of regexes — apply only if NONE match (feature missing)
    #   "present":      list of regexes — apply only if ALL match
    #   "any_present":  list of regexes — apply only if AT LEAST ONE matches
    # Empty/missing apply_when => always applicable (legacy behaviour).
    apply_when: Dict = field(default_factory=dict)

    @classmethod
    def from_dict(cls, d: Dict) -> "Transform":
        raw = str(d.get("placement", "preamble")).lower()
        append_words = ("append", "end of", "bottom", "final", "last", "seal")
        placement = "append" if any(w in raw for w in append_words) else "preamble"
        aw = d.get("apply_when") or {}
        if not isinstance(aw, dict):
            aw = {}
        return cls(
            id=d.get("id", ""),
            description=d.get("description", ""),
            trigger=d.get("trigger", ""),
            implementation=d.get("implementation", "").rstrip("\n"),
            placement=placement,
            apply_when=aw,
        )

    @staticmethod
    def _any(patterns, text: str) -> bool:
        return any(re.search(p, text, re.MULTILINE) for p in patterns)

    def applies_to_language(self, language: str) -> bool:
        want = self.apply_when.get("language")
        return want is None or want == language

    def matches(self, text: str, language: str = "shell") -> Tuple[bool, str]:
        """Decide whether this transform is needed for `text`.

        Returns (apply, human_reason). The reason powers APEX's self-driving
        narration ("detected X -> applying", "already has Y -> skipping").
        """
        if not self.applies_to_language(language):
            return False, "targets {0}, script is {1}".format(
                self.apply_when.get("language"), language)

        aw = self.apply_when
        if not aw:
            return True, "baseline transform (always applied)"

        present = aw.get("present") or []
        any_present = aw.get("any_present") or []
        absent = aw.get("absent") or []

        # present: every required marker must exist
        for p in present:
            if not re.search(p, text, re.MULTILINE):
                return False, "requires `{0}` in the script; not found".format(p)
        # any_present: at least one trigger pattern must exist
        if any_present and not self._any(any_present, text):
            return False, "no matching trigger pattern present"
        # absent: the feature must be missing for the block to be needed
        for a in absent:
            if re.search(a, text, re.MULTILINE):
                return False, "already present (matched `{0}`)".format(a)

        # Build an affirmative reason for why it fired.
        bits: List[str] = []
        if any_present:
            hit = next((p for p in any_present if re.search(p, text, re.MULTILINE)), None)
            if hit:
                bits.append("uses `{0}`".format(hit))
        if absent:
            bits.append("missing " + ", ".join("`{0}`".format(a) for a in absent[:3]))
        return True, ("; ".join(bits) if bits else "condition met")


@dataclass
class Rewrite:
    """A content-aware, idempotent rewrite of the script's OWN lines.

    Unlike a Transform (which injects a new block), a Rewrite substitutes a
    matched pattern in the user's code — e.g. `rm -rf X` -> `safe_rm X`. The
    engine applies it only over real code regions, validates the result, and
    rolls the rewrite back if it would break the script.

    Fields:
      pattern:            regex matched (MULTILINE) against the user's code.
      replacement:        re.sub template (may use \\1 / \\g<name> backrefs).
      requires_transform: id of a companion inject block that MUST be present
                          for the rewrite to be valid (the helper it calls).
      apply_when:         same gate dict as Transform (language/present/…).
    """
    id: str
    description: str
    pattern: str
    replacement: str
    requires_transform: str = ""
    apply_when: Dict = field(default_factory=dict)

    @classmethod
    def from_dict(cls, d: Dict) -> "Rewrite":
        aw = d.get("apply_when") or {}
        if not isinstance(aw, dict):
            aw = {}
        return cls(
            id=d.get("id", ""),
            description=d.get("description", ""),
            pattern=d.get("pattern", ""),
            replacement=d.get("replacement", ""),
            requires_transform=d.get("requires_transform", ""),
            apply_when=aw,
        )

    def gate(self, text: str, language: str = "shell") -> Tuple[bool, str]:
        """Evaluate the apply_when gate (language + present/any_present/absent)."""
        aw = self.apply_when
        want = aw.get("language")
        if want is not None and want != language:
            return False, "targets {0}, script is {1}".format(want, language)
        for p in aw.get("present") or []:
            if not re.search(p, text, re.MULTILINE):
                return False, "requires `{0}`; not found".format(p)
        anyp = aw.get("any_present") or []
        if anyp and not any(re.search(p, text, re.MULTILINE) for p in anyp):
            return False, "no matching trigger pattern present"
        for a in aw.get("absent") or []:
            if re.search(a, text, re.MULTILINE):
                return False, "already present (matched `{0}`)".format(a)
        return True, "gate met"


@dataclass
class Rubric:
    domain: str
    target_standard: str
    summary: str
    controls: List[Control] = field(default_factory=list)
    transforms: List[Transform] = field(default_factory=list)
    rewrites: List[Rewrite] = field(default_factory=list)
    llm_guidance: str = ""
    references: List[str] = field(default_factory=list)

    @classmethod
    def from_dict(cls, d: Dict) -> "Rubric":
        return cls(
            domain=d.get("domain", ""),
            target_standard=d.get("target_standard", ""),
            summary=d.get("summary", ""),
            controls=[Control.from_dict(c) for c in d.get("controls", [])],
            transforms=[Transform.from_dict(t) for t in d.get("deterministic_transforms", [])],
            rewrites=[Rewrite.from_dict(r) for r in d.get("deterministic_rewrites", [])],
            llm_guidance=d.get("llm_guidance", ""),
            references=list(d.get("references", [])),
        )

    @property
    def automatable_controls(self) -> List[Control]:
        return [c for c in self.controls if c.automatable]


def load_rubrics(rubric_dir: Optional[str] = None) -> Dict[str, Rubric]:
    """Load every rubrics/*.json into {domain_key: Rubric}."""
    directory = rubric_dir or RUBRIC_DIR
    rubrics: Dict[str, Rubric] = {}
    if not os.path.isdir(directory):
        return rubrics
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".json") or name == "classifier.json":
            continue
        path = os.path.join(directory, name)
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        key = os.path.splitext(name)[0]
        rubrics[key] = Rubric.from_dict(data)
    return rubrics
